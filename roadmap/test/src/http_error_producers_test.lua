local test = require("test")
local roadmap = require("roadmap")
local state = require("state")
local periods = require("periods")
return test.run_cases(function()
    test.describe("Roadmap refusal ownership", function()
        test.it("types the addressed roadmap absence as NOT_FOUND", function()
            local _, err = roadmap.thread_id_for({ find = function() return nil, nil end }, "addressed-id")
            test.is_true(errors.is(err, errors.NOT_FOUND))
        end)
        test.it("preserves a thread reader failure before rendering", function()
            local original = errors.new({ kind = errors.TIMEOUT, message = "opaque", retryable = false, details = { marker = "reader" } })
            local _, err = roadmap.thread_id_for({ find = function() return nil, original end }, "addressed-id")
            test.is_true(errors.is(err, errors.TIMEOUT))
            test.eq(err:retryable(), original:retryable())
            test.eq(err:details().marker, "reader")
        end)
        test.it("types invalid referenced entities separately from addressed resources", function()
            local failure = state.validate_command({}, state.EVENT.INITIATIVE_ADDED, { id = "initiative", title = "title", layer_id = "missing-reference" })
            test.is_true(errors.is(failure, errors.INVALID))
            test.contains(tostring(failure), "layer not found")
        end)
        test.it("types calendar validation before wrapping context", function()
            local _, err = periods.parse("2026-13", "month")
            test.is_true(errors.is(err, errors.INVALID))
        end)
    end)
end)

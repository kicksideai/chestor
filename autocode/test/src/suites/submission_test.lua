local test = require("test")
local json = require("json")
local subject = require("subject")
local stubs = require("stubs")
local function cases()
    test.describe("autocode canonical submission", function()
        test.it("leaves container stopping to the cancellation watcher", function()
            local state = stubs.reset()
            test.is_nil(subject.cancel("owner", "run"))
            test.is_true(state.run.cancel_requested)
            test.eq(state.stopped, 0)
        end)
        test.it("announces a committed queued run to the owner while workers are unavailable", function()
            local state = stubs.reset()
            local id, err = subject.submit({agent = "claude", account_id = "account", image_id = "image", options = {}, prompt = "task", repo_url = ""})
            test.is_nil(err, tostring(err))
            test.eq(id, "queued-run")
            test.eq(state.run.status, "queued")
            test.eq(state.nudges, 1)
            test.not_nil(state.notifications)
            test.eq(#state.notifications, 1)
            test.eq(state.notifications[1].owner, state.created.owner)
            test.eq(state.notifications[1].topic, stubs.live.RUNS_TOPIC)
            test.is_true(state.notifications[1].committed)
        end)
        test.it("returns the committed run ID when notification fails and still nudges workers", function()
            local state = stubs.reset()
            state.notify_error = errors.new({kind = errors.UNAVAILABLE, message = "notify unavailable"})
            local id, err = subject.submit({agent = "claude", account_id = "account", image_id = "image", options = {}, prompt = "task", repo_url = ""})
            test.eq(id, "queued-run")
            test.is_nil(err, tostring(err))
            test.eq(state.run.status, "queued")
            test.eq(state.nudges, 1)
            test.not_nil(state.notifications)
        end)
        test.it("does not announce a failed submission commit", function()
            local state = stubs.reset()
            state.create_run_error = errors.new({kind = errors.UNAVAILABLE, message = "commit failed"})
            local id, err = subject.submit({agent = "claude", account_id = "account", image_id = "image", options = {}, prompt = "task", repo_url = ""})
            test.is_nil(id)
            test.is_true(errors.is(err, errors.UNAVAILABLE))
            test.is_nil(state.notifications)
        end)
        test.it("distinguishes nested empty arrays and objects while sorting object keys", function()
            local function canonical(options)
                local state = stubs.reset()
                local id, err = subject.submit({agent = "claude", image_id = "image", options = json.decode(options), prompt = "task", repo_url = ""}, nil, "key")
                test.is_nil(err)
                test.eq(id, "existing")
                return state.submission.canonical
            end
            test.is_true(canonical('{"nested":[]}') ~= canonical('{"nested":{}}'))
            test.is_true(canonical('{"nested":[{"leaf":[]}]}') ~= canonical('{"nested":[{"leaf":{}}]}'))
            test.eq(canonical('{"b":{},"a":[[]]}'), canonical('{"a":[[]],"b":{}}'))
        end)
    end)
end
local run_cases = test.run_cases(cases)
return {run = function(options) return run_cases(options) end}

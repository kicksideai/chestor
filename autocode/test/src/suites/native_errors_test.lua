local test = require("test")
local stubs = require("stubs")
local arm = require("arm")
local live = require("live")
local function cases()
    test.describe("autocode native error context", function()
        test.after_each(function() stubs.reset() end)
        local function fault()
            return errors.new({kind = errors.PERMISSION_DENIED, message = "denied", retryable = false, details = {code = "native.denied"}})
        end
        local function check(err)
            test.is_true(errors.is(err, errors.PERMISSION_DENIED), tostring(err))
            test.eq(err:retryable(), false)
            test.eq(err:details().code, "native.denied")
        end
        test.it("does not publish a card for an account deleted during execution", function()
            local state = stubs.reset()
            state.account_projection_error = errors.new({kind = errors.NOT_FOUND, message = "deleted"})
            test.is_nil(live.account("deleted"))
            test.is_nil(state.image_notifies)
        end)
        test.it("preserves native Flow read errors at the Block boundary", function()
            local state = stubs.reset()
            state.flow_error = fault()
            local value, err = arm.arm({dataflow_id = "flow", config = {}})
            test.is_nil(value)
            check(err)
        end)
        test.it("preserves native realtime notification errors", function()
            local state = stubs.reset()
            state.realtime_error = fault()
            check(live.notify("owner", "topic"))
        end)
    end)
end
local run_cases = test.run_cases(cases)
return {run = function(options) return run_cases(options) end}

local test = require("test")
local repo = require("repo")
local sql = require("sql")
local json = require("json")
local uuid = require("uuid")
local identity_helper = require("identity")
local account_health = require("account_health")
local redact = require("redact")
local time = require("time")

local function spec(account)
    return {agent = "claude", account_id = account, image_id = "image", options = {}, unattended = true,
        repo_url = "", prompt = "task", timeout_ms = 60000}
end
local identity = {actor_id = "test:actor", actor_context = "{}"}
local function await_pruned(id)
    local deadline = time.now():add("15s")
    repeat
        local _, err = repo.prune_runs("2999-01-01T00:00:00Z", 1000)
        test.is_nil(err, tostring(err))
        if not repo.stored_run(id) then return end
        test.is_false(time.now():after(deadline), "retention does not finish after job termination")
        time.sleep("10ms")
    until false
end
local function cases()
    test.describe("autocode persistence", function()
        test.it("enqueues the configured image deadline and rejects invalid bounds", function()
            local state = require("stubs").reset()
            local builds = require("builds_subject")
            local image, generation = uuid.v7(), uuid.v7()
            state.build_timeout = "2m"
            test.is_nil(builds.request_image_build(image, identity, "initial", generation))
            test.eq(state.enqueued.immutable_payload.max_execution_ms, 120000)
            test.is_nil(builds.delete_image_build(image))
            for _, duration in ipairs({"59s", "168h1ms"}) do
                state.build_timeout = duration
                local err = builds.request_image_build(uuid.v7(), identity, "initial", uuid.v7())
                test.is_true(errors.is(err, errors.INVALID), tostring(err))
            end
        end)
        test.it("skips active retention jobs and continues to later candidates", function()
            local stubs = require("stubs")
            local state = stubs.reset()
            local runs = require("run_store_subject")
            state.job_id = uuid.v7()
            local active = runs.create_run(uuid.v7(), identity, spec(uuid.v7()))
            state.job_id = uuid.v7()
            local terminal = runs.create_run(uuid.v7(), identity, spec(uuid.v7()))
            test.is_true(repo.finish_run(active, "succeeded", "", "", {}))
            test.is_true(repo.finish_run(terminal, "succeeded", "", "", {}))
            local one, two = repo.stored_run(active), repo.stored_run(terminal)
            state.jobs = {[one.job_id] = {status = "running"}, [two.job_id] = {status = "cancelled"}}
            local db = sql.get("app:db")
            test.is_nil(select(2, db:execute("UPDATE chestor_autocode_runs SET finished_at = $1 WHERE id = $2", {"0001", active})))
            test.is_nil(select(2, db:execute("UPDATE chestor_autocode_runs SET finished_at = $1 WHERE id = $2", {"0002", terminal})))
            db:release()
            local count, err = require("run_store_subject").prune_runs("0003", 500)
            test.is_nil(err, tostring(err))
            test.eq(count, 1)
            test.not_nil(repo.stored_run(active))
            test.is_nil(repo.stored_run(terminal))
        end)
        test.it("keeps the approved recipe across pending and failed refresh generations", function()
            local image, generation = uuid.v7(), uuid.v7()
            local recipe = require("stubs").recipe_fixture()
            recipe.ref = "sha256:" .. string.rep("a", 64)
            test.is_nil(repo.request_image_build(image, identity, "initial", generation))
            test.is_nil(repo.finish_image_build(image, "ok", generation, "ready", {"claude"}, "", recipe))
            test.is_nil(repo.project_image_build(image, generation, function() return nil end))
            local next_generation = uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "refresh", next_generation))
            test.eq(repo.image_build(image).approved_recipe.ref, recipe.ref)
            test.eq(repo.image_build(image).approved_agents[1], "claude")
            test.is_nil(repo.finish_image_build(image, "bad", next_generation, "failed", {}, "probe failed"))
            test.is_nil(repo.project_image_build(image, next_generation, function() return nil end))
            test.eq(repo.image_build(image).approved_recipe.ref, recipe.ref)
            local replacement = uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "refresh", replacement))
            recipe.ref = "sha256:" .. string.rep("b", 64)
            test.is_nil(repo.finish_image_build(image, "ok", replacement, "ready", {"claude"}, "", recipe))
            test.is_nil(repo.project_image_build(image, replacement, function() return nil end))
            test.eq(repo.image_build(image).approved_recipe.ref, recipe.ref)
        end)
        test.it("persists caller pinning, JSON input and repository ref independently", function()
            for _, pinned in ipairs({false, true}) do
                local request = spec(uuid.v7())
                request.account_pinned, request.input, request.repo_ref = pinned, '{"value":42}', "release/v1"
                local id, err = repo.create_run(uuid.v7(), identity, request)
                test.is_nil(err)
                local stored = repo.stored_run(id)
                test.eq(stored.account_pinned, pinned)
                test.eq(stored.input, request.input)
                test.eq(stored.repo_ref, request.repo_ref)
            end
        end)
        test.it("creates a canonical trace for build jobs", function()
            local image_id, build_id = uuid.v7(), uuid.v7()
            test.is_nil(repo.request_image_build(image_id, identity, "initial", build_id))
            local build = repo.image_build(image_id)
            local db = sql.get("app:db")
            local rows = db:query("SELECT payload FROM kickside_job WHERE id = $1", {build.job_id})
            db:release()
            local payload = type(rows[1].payload) == "string" and json.decode(rows[1].payload) or rows[1].payload
            test.not_nil(payload.trace_context)
            test.eq(payload.trace_context.trace_id, payload.trace_context.run_id)
            test.is_true(#payload.trace_context.trace_id > 0)
        end)
        test.it("carries canonical trace context from a run job into its resume job", function()
            local input = spec(uuid.v7())
            local trace = {trace_id = "trace", run_id = "workflow", caused_by_event_id = "event", correlation_key = "key"}
            input.trace_context = trace
            input.flow = {dataflow_id = "flow", signal_id = "signal"}
            local id, err = repo.create_run(uuid.v7(), identity, input)
            test.is_nil(err)
            local stored = repo.stored_run(id)
            local db = sql.get("app:db")
            local rows = db:query("SELECT payload FROM kickside_job WHERE id = $1", {stored.job_id})
            local payload = type(rows[1].payload) == "string" and json.decode(rows[1].payload) or rows[1].payload
            for key, value in pairs(trace) do test.eq(payload.trace_context and payload.trace_context[key], value) end
            local settled, settle_err = repo.finish_run(id, "succeeded", "done", "", {}, trace)
            test.is_nil(settle_err)
            test.is_true(settled)
            local resumes = db:query("SELECT payload FROM kickside_job WHERE job_type = $1 AND owner_id = $2", {"chestor.autocode.blocks:resume", stored.owner_id})
            db:release()
            local resumed = type(resumes[1].payload) == "string" and json.decode(resumes[1].payload) or resumes[1].payload
            for key, value in pairs(trace) do test.eq(resumed.trace_context and resumed.trace_context[key], value) end
        end)
        test.it("replays a caller key without another run or job", function()
            local key = uuid.v7()
            local owner = uuid.v7()
            local first, err = repo.create_run(owner, identity, spec("a"), {key = key, canonical = "request"})
            test.is_nil(err)
            local second, replay_err = repo.create_run(owner, identity, spec("a"), {key = key, canonical = "request"})
            test.is_nil(replay_err)
            test.eq(first, second)
            local stored = repo.stored_run(first)
            test.not_nil(stored.job_id)
            local db = sql.get("app:db")
            local rows = db:query("SELECT id FROM kickside_job WHERE id = $1", {stored.job_id})
            db:release()
            test.eq(#rows, 1)
            test.eq(rows[1].id, stored.job_id)
            local changed, conflict = repo.create_run(owner, identity, spec("a"), {key = key, canonical = "changed"})
            test.is_nil(changed)
            test.is_true(errors.is(conflict, errors.CONFLICT))
            local separate = repo.create_run(uuid.v7(), identity, spec("a"), {key = key, canonical = "request"})
            test.is_true(separate ~= first)
        end)

        test.it("reserves the least recently submitted account inside the run transaction", function()
            local a, b = uuid.v7(), uuid.v7()
            local request = spec(a)
            local first, err = repo.create_run(uuid.v7(), identity, request, nil, {b, a})
            test.is_nil(err)
            local second, next_err = repo.create_run(uuid.v7(), identity, spec(a), nil, {b, a})
            test.is_nil(next_err)
            local one, two = repo.stored_run(first), repo.stored_run(second)
            test.is_true(one.account_id ~= two.account_id)
        end)

        test.it("uses reservation order when account timestamps tie", function()
            local a, b = uuid.v7(), uuid.v7()
            local first = repo.create_run(uuid.v7(), identity, spec(a), nil, {a, b})
            local one = repo.stored_run(first)
            local db = sql.get("app:db")
            local _, err = db:execute("UPDATE chestor_autocode_account_state SET last_used_at = '2000-01-01T00:00:00Z' WHERE account_id IN ($1, $2)", {a, b})
            db:release()
            test.is_nil(err)
            local second = repo.create_run(uuid.v7(), identity, spec(a), nil, {a, b})
            test.is_true(repo.stored_run(second).account_id ~= one.account_id)
        end)

        test.it("never recreates deleted account state on successful or failed settlement", function()
            for _, failed in ipairs({false, true}) do
                local user = identity_helper.member()
                local created = identity_helper.request(user, "POST", "/autocode/accounts", {
                    agent = "claude", credential_kind = "env:ANTHROPIC_API_KEY", label = "deleted in flight", secret = "key"})
                test.eq(created.status, 201, created.body)
                local account = created.json.id
                require("stubs").reset()
                local id = require("run_store_subject").create_run(user.id, identity, spec(account), nil, {account})
                test.is_true(repo.start_run(id))
                local removed = identity_helper.request(user, "DELETE", "/autocode/accounts/" .. account)
                test.eq(removed.status, 200, removed.body)
                local emitted = {}
                account_health.settle(repo.stored_run(id), failed and {outcome = "failed", error = {
                    code = "rate_limit", message = "rate limited", retryable = true}} or {outcome = "succeeded"},
                    failed and "credential refresh failed" or nil, redact.new("key"),
                    function(_, text) emitted[#emitted + 1] = text end)
                test.eq(#emitted, 0)
                test.is_true(repo.finish_run(id, failed and "failed" or "succeeded", "", "", {}))
                local db = sql.get("app:db")
                local rows = db:query("SELECT account_id FROM chestor_autocode_account_state WHERE account_id = $1", {account})
                db:release()
                test.eq(#rows, 0)
                identity_helper.release(user)
            end
        end)
        test.it("preserves a newer refusal when an older run succeeds", function()
            local account = uuid.v7()
            repo.create_run(uuid.v7(), identity, spec(account), nil, {account})
            test.is_nil(repo.settle_account(account, "rate limited", "2999-01-01T00:00:00Z"))
            test.is_nil(repo.settle_account(account, "", "", "2000-01-01T00:00:00Z"))
            local states = repo.account_states({account})
            test.eq(states[account].last_error, "rate limited")
        end)

        test.it("retains settled workflow runs until delivery is acknowledged", function()
            local request = spec(uuid.v7())
            request.flow = {dataflow_id = "flow", signal_id = "signal"}
            local id, err = repo.create_run(uuid.v7(), identity, request)
            test.is_nil(err)
            test.is_true(repo.finish_run(id, "succeeded", "answer", "", {}))
            test.is_nil(repo.append_event(id, 2, "system", "finished"))
            local _, prune_err = repo.prune_runs("2999-01-01T00:00:00Z", 1000)
            test.is_nil(prune_err)
            test.not_nil(repo.stored_run(id))
            test.is_nil(repo.acknowledge_delivery(id))
            await_pruned(id)
            test.is_nil(repo.stored_run(id))
        end)

        test.it("replays an image generation without enqueueing another build", function()
            local image, generation = uuid.v7(), uuid.v7()
            local requester = {actor_id = uuid.v7(), actor_context = "{}"}
            test.is_nil(repo.request_image_build(image, requester, "initial", generation))
            local job_id = repo.image_build(image).job_id
            test.is_true(job_id ~= "")
            test.is_nil(repo.request_image_build(image, requester, "initial", generation))
            test.eq(repo.image_build(image).job_id, job_id)
            local db = sql.get("app:db")
            local rows, read_err = db:query("SELECT id FROM kickside_job WHERE owner_id = $1 AND job_type = 'chestor.autocode.runner:image'", {requester.actor_id})
            db:release()
            test.is_nil(read_err)
            test.eq(#rows, 1)
            test.eq(rows[1].id, job_id)
        end)

        test.it("rolls back a build request when Jobs rejects its owner", function()
            local image, generation = uuid.v7(), uuid.v7()
            local err = repo.request_image_build(image, {actor_id = "", actor_context = "{}"}, "initial", generation)
            test.not_nil(err)
            test.is_nil(repo.image_build(image))
            test.is_nil(repo.request_image_build(image, identity, "initial", generation))
            local job_id = repo.image_build(image).job_id
            local err = repo.request_image_build(image, {actor_id = "", actor_context = "{}"}, "refresh", uuid.v7(), generation)
            test.not_nil(err)
            test.eq(repo.image_build(image).build_id, generation)
            test.eq(repo.image_build(image).job_id, job_id)
        end)
        test.it("rolls back a build request when Jobs returns no ID", function()
            local state = require("stubs").reset()
            state.job_id = ""
            local image, generation = uuid.v7(), uuid.v7()
            local err = require("builds_subject").request_image_build(image, identity, "initial", generation)
            test.eq(err:message(), "image build enqueue returns no job ID")
            test.eq(state.enqueued.key, "build:" .. generation)
            test.eq(state.enqueued.job_type, "chestor.autocode.runner:image")
            test.eq(state.enqueued.owner_locator.id, identity.actor_id)
            test.eq(state.enqueued.max_attempts, 3)
            test.eq(state.enqueued.immutable_payload.image_id, image)
            test.eq(state.enqueued.immutable_payload.build_id, generation)
            test.eq(state.enqueued.immutable_payload.max_execution_ms, 1800000)
            test.is_nil(repo.image_build(image))
        end)

        test.it("retains the enqueued job ID and replaces only the abandoned generation", function()
            local image, generation = uuid.v7(), uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "initial", generation))
            test.is_true(repo.image_build(image).job_id ~= "")
            local replacement = uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "refresh", replacement, generation))
            test.eq(repo.image_build(image).build_id, replacement)
            test.not_nil(repo.request_image_build(image, identity, "refresh", uuid.v7(), generation))
            test.not_nil(repo.finish_image_build(image, "stale", generation, "failed", {}, "old"))
        end)

        test.it("atomically claims a build generation and fences stale completion", function()
            local image, generation = uuid.v7(), uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "initial", generation))
            local err = repo.request_image_build(image, identity, "refresh", uuid.v7())
            test.is_true(errors.is(err, errors.CONFLICT))
            test.is_nil(repo.finish_image_build(image, "done", generation, "ready", {"claude"}, ""))
            local build = repo.image_build(image)
            test.eq(build.build_id, generation)
            test.eq(build.status, "ready")
            test.eq(build.agents[1], "claude")
            test.is_nil(repo.project_image_build(image, generation, function() return nil end))
            local next_generation = uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "refresh", next_generation))
            test.not_nil(repo.finish_image_build(image, "stale", generation, "failed", {}, "old"))
            test.eq(repo.image_build(image).build_id, next_generation)
        end)
        test.it("rejects a nonempty persisted recipe without a revision", function()
            local image, generation = uuid.v7(), uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "initial", generation))
            local db = sql.get("app:db")
            local _, err = db:execute("UPDATE chestor_autocode_image_builds SET recipe = $1 WHERE image_id = $2",
                {'{"ref":"image","home":"/opt/agent","settings":{"memory":"","cpus":"","pids_limit":0,"gpus":"","network":"none","extra_args":[],"allows":[]}}', image})
            db:release()
            test.is_nil(err)
            local build, read_err = repo.image_build(image)
            test.is_nil(build)
            test.eq(read_err:details().code, "autocode.invalid_recipe")
        end)
        test.it("rolls back run, reservation and caller key when job creation fails", function()
            local account, owner, key = uuid.v7(), uuid.v7(), uuid.v7()
            local db = sql.get("app:db")
            local rows = db:query("SELECT generation FROM chestor_autocode_admission_lock WHERE id = 1", {})
            local before = rows[1].generation
            db:release()
            -- Jobs rejects an empty owner locator after the run and key inserts.
            local id, err = repo.create_run("", identity, spec(account), {key = key, canonical = "request"})
            test.is_nil(id)
            test.not_nil(err)
            db = sql.get("app:db")
            rows = db:query("SELECT generation FROM chestor_autocode_admission_lock WHERE id = 1", {})
            test.eq(rows[1].generation, before)
            rows = db:query("SELECT id FROM chestor_autocode_runs WHERE account_id = $1", {account})
            test.eq(#rows, 0)
            rows = db:query("SELECT account_id FROM chestor_autocode_account_state WHERE account_id = $1", {account})
            test.eq(#rows, 0)
            rows = db:query("SELECT run_id FROM chestor_autocode_submissions WHERE key = $1", {key})
            db:release()
            test.eq(#rows, 0)
            test.not_nil(repo.create_run(owner, identity, spec(account), {key = key, canonical = "request"}))
        end)
        test.it("returns a typed error for malformed persisted recipe settings", function()
            local image, generation = uuid.v7(), uuid.v7()
            test.is_nil(repo.request_image_build(image, identity, "initial", generation))
            local db = sql.get("app:db")
            local _, err = db:execute("UPDATE chestor_autocode_image_builds SET recipe = $1 WHERE image_id = $2",
                {'{"ref":"image","home":"/opt/agent","revision":1,"settings":{"pids_limit":"broken"}}', image})
            db:release()
            test.is_nil(err)
            local build, read_err = repo.image_build(image)
            test.is_nil(build)
            test.is_true(errors.is(read_err, errors.INTERNAL))
            test.eq(read_err:details().code, "autocode.invalid_recipe")
        end)
        test.it("prunes an orphan container after retention removes its settled run", function()
            local id, err = repo.create_run(uuid.v7(), identity, spec(uuid.v7()))
            test.is_nil(err)
            test.is_true(repo.finish_run(id, "succeeded", "answer", "", {}))
            await_pruned(id)
            test.is_nil(repo.stored_run(id))
            local state = require("stubs").reset()
            state.containers = {"retained-box " .. id}
            test.not_nil(require("maintenance").prune())
            test.eq(state.removed, 1)
            test.eq(state.removed_names[1], "retained-box")
        end)
        test.it("retains build rows until the public Jobs cancellation confirms termination", function()
            local image, generation = uuid.v7(), uuid.v7()
            local state = require("stubs").reset()
            state.job = {status = "running"}
            state.job_id = "active-job"
            local builds = require("builds_subject")
            test.is_nil(builds.request_image_build(image, identity, "initial", generation))
            test.not_nil(builds.delete_image_build(image))
            test.eq(state.cancelled_job, "active-job")
            test.not_nil(repo.image_build(image))
            state.job.status = "cancelled"
            test.is_nil(builds.delete_image_build(image))
            test.is_nil(repo.image_build(image))
        end)
        test.it("keeps public metadata authoritative when a build is abandoned", function()
            local state = require("stubs").reset()
            state.job = {status = "dead"}
            state.job_id = "dead-job"
            local image, generation = uuid.v7(), uuid.v7()
            local builds = require("builds_subject")
            test.is_nil(builds.request_image_build(image, identity, "initial", generation))
            local build, err = builds.image_build(image)
            test.is_nil(err)
            local projected = require("resource_dto").image({id = image, meta = {status = "preparing"}, owner = "owner", access = 15}, build)
            test.eq(projected.status, "preparing")
            state.job_error = true
            local unavailable, read_err = builds.image_build(image)
            test.is_nil(unavailable)
            test.is_true(errors.is(read_err, errors.UNAVAILABLE))
        end)
        test.it("records the pending result durably before the terminal transaction", function()
            require("stubs").reset()
            local id, err = require("run_store_subject").create_run(uuid.v7(), identity, spec(uuid.v7()))
            test.is_nil(err)
            test.is_nil(repo.record_run_outcome(id, "succeeded", "complete answer", "", {input_tokens = 42}))
            local stored = repo.stored_run(id)
            test.eq(stored.status, "queued")
            test.eq(stored.pending_status, "succeeded")
            test.eq(stored.result, "complete answer")
            test.eq(stored.usage.input_tokens, 42)
            test.is_nil(repo.record_run_outcome(id, "failed", "", "retry", {}))
            test.eq(repo.stored_run(id).pending_status, "succeeded")
            test.is_true(repo.finish_run(id, stored.pending_status, stored.result, stored.error, stored.usage))
            test.is_false(repo.finish_run(id, "failed", "", "duplicate", {}))
        end)
    end)
end
local run_cases = test.run_cases(cases)
return {run = function(options) return run_cases(options) end}

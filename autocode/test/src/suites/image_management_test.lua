local test = require("test")
local subject = require("subject")
local stubs = require("stubs")
local teardown = require("teardown")
local function cases()
    test.describe("autocode image management", function()
        test.it("carries optional Docker removal in asynchronous deletion without removing a live reference", function()
            local state = stubs.reset()
            state.delete_result = {deleted = false, in_progress = true, job_id = "delete-job"}
            local result, err = subject.delete({id = "image", remove = true})
            test.is_nil(err, tostring(err))
            test.is_true(result.in_progress)
            test.eq(#state.commands, 0)
            test.eq(state.delete_options.remove, true)
        end)
        test.it("registers an unprepared image before enqueue", function()
            local state = stubs.reset()
            state.build = nil
            test.not_nil(subject.create({ref = "image:tag"}))
            test.eq(state.registered.meta.status, "unprepared")
            test.not_nil(state.requested_build)
        end)
        test.it("saves ref and Dockerfile changes and rebuilds their new recipe", function()
            local state = stubs.reset()
            local result, err = subject.update({id = "image", ref = "new:tag", dockerfile = "FROM base"})
            test.is_nil(err)
            test.not_nil(result)
            test.eq(state.replacements[1].fields.ref, "new:tag")
            test.eq(state.replacements[2].fields.status, "preparing")
            test.eq(state.replacements[1].patch.dockerfile, "FROM base")
            test.eq(state.requested_build.mode, "initial")
        end)
        test.it("refreshes a changed registry reference without a Dockerfile", function()
            local state = stubs.reset()
            test.not_nil(subject.update({id = "image", ref = "new:tag"}))
            test.eq(state.requested_build.mode, "refresh")
        end)
        test.it("returns the created identity and a typed error when build admission fails", function()
            local state = stubs.reset()
            state.admission_error = true
            local result, err = subject.create({ref = "image:tag"})
            test.is_nil(err)
            test.eq(result.id, "created")
            test.eq(result.build_error.kind, errors.UNAVAILABLE)
            test.eq(result.build_error.retryable, false)
            test.not_nil(result.build_error.details.code)
            test.eq(state.registered.meta.status, "unprepared")
            test.is_nil(state.replaced)
            test.is_nil(state.meta_written)
        end)
        test.it("updates image metadata and settings in one revision-checked command batch", function()
            local state = stubs.reset()
            local result, err = subject.update({id = "image", label = "renamed", memory = "8g"})
            test.is_nil(err)
            test.not_nil(result)
            test.not_nil(state.replaced)
            test.eq(state.replacements[1].fields.title, "renamed")
            test.eq(state.replacements[1].patch.settings.memory, "8g")
            test.eq(state.replacements[1].revision, 7)
            test.eq(state.replacements[1].fields.status, "unprepared")
            test.is_nil(state.meta_written)
            test.is_nil(state.patched)
            test.not_nil(state.requested_build)
            test.eq(state.requested_build.mode, "initial")
            test.eq(state.requested_build.identity.actor_id, "owner")
        end)
        test.it("keeps a label-only edit ready", function()
            local state = stubs.reset()
            local result, err = subject.update({id = "image", label = "renamed", home = "/opt/agent"})
            test.is_nil(err)
            test.not_nil(result)
            test.is_nil(state.replacements[1].fields.status)
            test.is_nil(state.requested_build)
        end)
        test.it("returns partial success after saving settings when preparation cannot start", function()
            local state = stubs.reset()
            state.admission_error = true
            local result, err = subject.update({id = "image", memory = "8g"})
            test.is_nil(err)
            test.eq(result.id, "image")
            test.eq(result.build_error.kind, errors.UNAVAILABLE)
            test.eq(state.replacements[1].fields.status, "unprepared")
            test.eq(state.replacements[1].patch.settings.memory, "8g")
        end)
        test.it("refuses a settings change during an active build without saving it", function()
            local state = stubs.reset()
            state.build = {build_id = "running", job_id = "job", finished_at = "", projected = false}
            state.job = {id = "job", status = "running"}
            local result, err = subject.update({id = "image", memory = "8g"})
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.is_nil(state.replaced)
            test.is_nil(state.requested_build)
        end)
        test.it("prepares an unprepared image when a save repeats its committed settings", function()
            local state = stubs.reset()
            state.image_status = "unprepared"
            local result, err = subject.update({id = "image", label = "image", home = "/opt/agent"})
            test.is_nil(err)
            test.not_nil(result)
            test.is_nil(state.replacements[1].patch)
            test.not_nil(state.requested_build)
            test.eq(state.requested_build.mode, "initial")
        end)
        test.it("saves a label-only edit during an active build", function()
            local state = stubs.reset()
            state.build = {build_id = "running", job_id = "job", finished_at = "", projected = false}
            state.job = {id = "job", status = "running"}
            local result, err = subject.update({id = "image", label = "renamed", home = "/opt/agent"})
            test.is_nil(err)
            test.not_nil(result)
            test.eq(state.replacements[1].fields.title, "renamed")
        end)
        test.it("does not request a build when the settings revision conflicts", function()
            local state = stubs.reset()
            state.replace_conflict = true
            local result, err = subject.update({id = "image", memory = "8g"})
            test.is_nil(result)
            test.is_true(errors.is(err, errors.CONFLICT))
            test.is_nil(state.requested_build)
        end)
        test.it("does not remove Docker references when component deletion fails", function()
            local state = stubs.reset()
            state.delete_error = errors.new({kind = errors.UNAVAILABLE, message = "build termination failed"})
            local result, err = subject.delete({id = "image", remove = true})
            test.is_nil(result)
            test.is_true(errors.is(err, errors.UNAVAILABLE))
            test.eq(#state.commands, 0)
        end)
        test.it("drains the build before removing the reference it can recreate", function()
            local state = stubs.reset()
            state.build.approved_recipe = {ref = "image"}
            state.on_delete = function() test.eq(#state.commands, 0) end
            test.is_true(teardown.delete_image({options = {remove = true}}).success)
            test.eq(state.commands[#state.commands], "image rm image")
        end)
        test.it("confirms image absence with machine-readable image listing", function()
            local state = stubs.reset()
            state.build.approved_recipe = {ref = "image"}
            state.docker_steps = {{code = 1, lines = {"missing image in any locale"}}, {code = 0}}
            local result, err = teardown.delete_image({options = {remove = true}})
            test.is_nil(err)
            test.not_nil(result)
            test.not_nil(state.docker_commands[2]:find("--format", 1, true))
        end)
        test.it("preserves a daemon failure instead of classifying it as image use", function()
            local state = stubs.reset()
            state.build.approved_recipe = {ref = "image"}
            state.docker_steps = {{code = 1, lines = {"daemon unavailable"}}, {code = 1, lines = {"daemon unavailable"}}}
            local result, err = teardown.delete_image({options = {remove = true}})
            test.is_nil(err)
            test.is_false(result.success)
            test.eq(result.error:kind(), errors.UNAVAILABLE)
            test.eq(result.error:details().output, "daemon unavailable")
        end)
        test.it("classifies confirmed container use without reading human Docker output", function()
            local state = stubs.reset()
            state.build.approved_recipe = {ref = "image"}
            state.docker_steps = {{code = 1, lines = {"localized failure"}}, {lines = {"sha256:image image latest <none>"}}, {lines = {"box"}}, {lines = {"sha256:image"}}}
            local result, err = teardown.delete_image({options = {remove = true}})
            test.is_nil(err)
            test.is_false(result.success)
            test.eq(result.error:kind(), errors.CONFLICT)
            test.eq(result.error:details().output, "localized failure")
            test.eq(#state.docker_steps, 0)
        end)
        test.it("preserves native Docker permission errors", function()
            local state = stubs.reset()
            state.build.approved_recipe = {ref = "image"}
            local denied = errors.new({kind = errors.PERMISSION_DENIED, message = "executor denied", details = {code = "host_denied"}})
            state.docker_steps = {{err = denied}}
            local result, err = teardown.delete_image({options = {remove = true}})
            test.is_nil(err)
            test.is_false(result.success)
            test.eq(result.error:kind(), errors.PERMISSION_DENIED)
            test.eq(result.error:details().code, "host_denied")
        end)
        test.it("keeps a nonzero image deletion error when no container confirms use", function()
            local state = stubs.reset()
            state.build.approved_recipe = {ref = "image"}
            state.docker_steps = {{code = 1, lines = {"permission failure"}}, {lines = {"sha256:image image latest <none>"}}, {}}
            local result, err = teardown.delete_image({options = {remove = true}})
            test.is_nil(err)
            test.is_false(result.success)
            test.eq(result.error:kind(), errors.UNAVAILABLE)
            test.eq(result.error:details().output, "permission failure")
            test.eq(result.error:details().exit_code, 1)
        end)
        test.it("recognizes a shortened image ID in the structured image listing", function()
            local state = stubs.reset()
            state.image_ref = "sha256:abc123"
            state.build.approved_recipe = {ref = state.image_ref}
            state.docker_steps = {{code = 1, lines = {"localized failure"}}, {lines = {"sha256:abc123def image latest <none>"}}, {lines = {"box"}}, {lines = {"sha256:abc123def"}}}
            local result, err = teardown.delete_image({options = {remove = true}})
            test.is_nil(err)
            test.is_false(result.success)
            test.eq(result.error:kind(), errors.CONFLICT)
        end)
    end)
end
local run_cases = test.run_cases(cases)
return {run = function(options) return run_cases(options) end}

local function shell(script)
    local executor = exec.get("app:docker")
    local proc, err = executor:exec(quote.line({"/bin/sh", "-ec", script}), {})
    if not proc then error(tostring(err)) end
    local stream = proc:stdout_stream()
    assert(proc:start()); proc:close_stdin()
    local text = ""
    while true do local chunk = stream:read(4096); if not chunk then break end; text = text .. chunk end
    local code = proc:wait()
    stream:close(); proc:close(); executor:release()
    test.eq(code, 0, text)
    return (text:gsub("\n$", ""))
end
local function cases()
    test.describe("autocode real git worktrees", function()
        local root
        local image_ref = "chestor-autocode-worktree-test:" .. uuid.v7()
        test.before_all(function()
            local code, err = docker.run({"build", "-t", image_ref, "-"}, {stdin = "FROM debian:bookworm-slim\nRUN apt-get update && apt-get install -y --no-install-recommends git && rm -rf /var/lib/apt/lists/*\n"})
            test.is_nil(err); test.eq(code, 0)
        end)
        test.after_all(function()
            local code, err = docker.run({"image", "rm", image_ref})
            test.is_nil(err); test.eq(code, 0)
        end)
        test.before_each(function()
            local state = stubs.reset()
            state.executor, state.roots = "app:docker", "/"
            root = shell("pwd") .. "/.wippy/isolation-" .. uuid.v7()
            shell("mkdir -p " .. quote.posix(root) .. " && git init -q " .. quote.posix(root) .. " && git -C " .. quote.posix(root) .. " -c user.name=Test -c user.email=test@example.com commit -q --allow-empty -m initial")
        end)
        test.after_each(function()
            if root then
                local db = sql.get("app:db")
                db:execute("DELETE FROM chestor_autocode_runs WHERE owner_id = $1", {root}); db:release()
                shell("rm -rf -- " .. quote.posix(root))
            end
        end)
        test.it("refuses missing directories and symlinks outside the configured filesystem ceiling", function()
            local state = stubs.state
            state.roots = root
            shell("ln -s / " .. quote.posix(root .. "/escape"))
            local escaped = paths.verify({path = root .. "/escape"})
            test.is_nil(escaped)
            local missing = paths.verify({path = root .. "/missing"})
            test.is_nil(missing)
            test.is_true(paths.verify({path = root}))
        end)
        test.it("container Git metadata cannot install host hooks or configuration", function()
            local tree = trees.plan(root, "metadata-attack")
            test.is_nil(trees.create(tree))
            local code, err = docker.run({"run", "--rm", "--user", shell("id -u") .. ":" .. shell("id -g"), "--mount", "type=bind,source=" .. tree.path .. ",target=/workspace", "--mount", "type=bind,source=" .. tree.gitdir .. ",target=" .. tree.gitdir .. ",readonly", "--mount", "type=bind,source=" .. tree.path .. "/.git,target=/workspace/.git,readonly", image_ref, "sh", "-ec",
                "mkdir /workspace/hooks && printf '#!/bin/sh\\ntouch " .. root .. "/HOST-EXECUTED\\n' > /workspace/hooks/post-checkout && chmod +x /workspace/hooks/post-checkout && " ..
                "! rm /workspace/.git && ! cp /workspace/hooks/post-checkout " .. quote.posix(tree.gitdir .. "/hooks/post-checkout") ..
                " && ! git -c safe.directory=/workspace -C /workspace config core.hooksPath /workspace/hooks && ! git -c safe.directory=/workspace -C /workspace config core.fsmonitor /workspace/hooks/post-checkout && printf changed > /workspace/result"}, {})
            test.is_nil(err); test.eq(code, 0)
            test.is_nil(trees.remove(tree))
            shell("git -C " .. quote.posix(root) .. " cat-file -e autocode/metadata-attack:result && test ! -e " .. quote.posix(root .. "/HOST-EXECUTED"))
        end)
        test.it("captures source files without executing worktree-selected Git filters", function()
            shell("git -C " .. quote.posix(root) .. " config filter.attack.clean './host-filter.sh'")
            local tree = trees.plan(root, "filter-attack")
            test.is_nil(trees.create(tree))
            local script = "#!/bin/sh\ntouch " .. quote.posix(root .. "/HOST-EXECUTED") .. "\ncat\n"
            shell("printf %s " .. quote.posix(script) .. " > " .. quote.posix(tree.path .. "/host-filter.sh") .. " && chmod +x " .. quote.posix(tree.path .. "/host-filter.sh") .. " && printf '* filter=attack' > " .. quote.posix(tree.path .. "/.gitattributes"))
            test.is_nil(trees.remove(tree))
            shell("test ! -e " .. quote.posix(root .. "/HOST-EXECUTED"))
        end)
        test.it("creates a tree without executing worktree-selected Git smudge filters", function()
            local script = "#!/bin/sh\ntouch " .. quote.posix(root .. "/HOST-EXECUTED") .. "\ncat\n"
            shell("printf %s " .. quote.posix(script) .. " > " .. quote.posix(root .. "/host-filter.sh") .. " && chmod +x " .. quote.posix(root .. "/host-filter.sh") .. " && printf '* filter=attack' > " .. quote.posix(root .. "/.gitattributes") .. " && git -C " .. quote.posix(root) .. " add . && git -C " .. quote.posix(root) .. " -c user.name=Test -c user.email=test@example.com commit -qm filter && git -C " .. quote.posix(root) .. " config filter.attack.smudge './host-filter.sh'")
            local tree = trees.plan(root, "smudge-attack")
            test.is_nil(trees.create(tree))
            shell("test ! -e " .. quote.posix(root .. "/HOST-EXECUTED"))
            test.is_nil(trees.remove(tree))
        end)
        test.it("refuses pre-existing symlinks at every worktree path component", function()
            local outside = root .. "/outside"
            shell("mkdir " .. quote.posix(outside) .. " && ln -s " .. quote.posix(outside) .. " " .. quote.posix(root .. "/.autocode-runs"))
            local tree, err = trees.plan(root, "escape")
            test.is_nil(tree); test.not_nil(err)
            shell("test ! -e " .. quote.posix(outside .. "/escape"))
        end)
        test.it("two concurrent trees keep uncommitted files private and preserve both branches", function()
            shell("touch " .. quote.posix(root .. "/shared-only"))
            local a, b = trees.plan(root, "a"), trees.plan(root, "b")
            local done = channel.new(2)
            for _, tree in ipairs({a, b}) do coroutine.spawn(function() done:send(trees.create(tree) or true) end) end
            test.eq(done:receive(), true); test.eq(done:receive(), true)
            for index, tree in ipairs({a, b}) do
                local branch = "ticket-" .. tostring(index)
                shell("cd " .. quote.posix(tree.path) .. " && test ! -e shared-only && test ! -e ticket-" .. tostring(3-index) .. " && git switch -qc " .. branch .. " && touch " .. branch .. " && git add . && git -c user.name=Test -c user.email=test@example.com commit -qm " .. branch)
            end
            test.is_nil(trees.remove(a)); test.is_nil(trees.remove(b)); test.is_nil(trees.remove(a))
            test.eq(shell("git -C " .. quote.posix(root) .. " for-each-ref --format='%(refname)' refs/heads/autocode/"), "")
            shell("git -C " .. quote.posix(root) .. " cat-file -e ticket-1:ticket-1 && git -C " .. quote.posix(root) .. " cat-file -e ticket-2:ticket-2 && test ! -e " .. quote.posix(a.path) .. " && test ! -e " .. quote.posix(b.path))
        end)
        test.it("concurrent container mounts expose only their own tree and retain both commits", function()
            local a, b = trees.plan(root, "container-a"), trees.plan(root, "container-b")
            test.is_nil(trees.create(a)); test.is_nil(trees.create(b))
            local done = channel.new(2)
            local uid = shell("id -u") .. ":" .. shell("id -g")
            for index, tree in ipairs({a, b}) do
                coroutine.spawn(function()
                    local other = index == 1 and b or a
                    local branch = "container-ticket-" .. tostring(index)
                    local script = "test ! -e " .. quote.posix(other.path) .. " && test ! -e shared-only && touch " .. branch
                    local lines = {}
                    local code, err = docker.run({"run", "--rm", "--user", uid, "--network", "none", "--workdir", "/workspace", "--mount", "type=bind,source=" .. tree.path .. ",target=/workspace", "--mount", "type=bind,source=" .. tree.gitdir .. ",target=" .. tree.gitdir .. ",readonly", "--mount", "type=bind,source=" .. tree.path .. "/.git,target=/workspace/.git,readonly", image_ref, "sh", "-ec", script}, {on_line = function(line) lines[#lines + 1] = line end})
                    done:send({code = code, error = err, output = table.concat(lines, "\n")})
                end)
            end
            for _ = 1, 2 do local result = done:receive(); test.is_nil(result.error); test.eq(result.code, 0, result.output) end
            test.is_nil(trees.remove(a)); test.is_nil(trees.remove(b))
            shell("git -C " .. quote.posix(root) .. " cat-file -e autocode/container-a:container-ticket-1 && git -C " .. quote.posix(root) .. " cat-file -e autocode/container-b:container-ticket-2")
        end)
        test.it("retains commits when the agent commits without creating its own branch", function()
            local tree = trees.plan(root, "automatic")
            test.is_nil(trees.create(tree))
            shell("cd " .. quote.posix(tree.path) .. " && touch committed && git add committed && git -c user.name=Test -c user.email=test@example.com commit -qm committed")
            test.is_nil(trees.remove(tree))
            shell("git -C " .. quote.posix(root) .. " cat-file -e autocode/automatic:committed")
        end)
        test.it("ignores its own preservation ref and removes a redundant ref on cleanup retry", function()
            local tree = trees.plan(root, "retry")
            test.is_nil(trees.create(tree))
            shell("git -C " .. quote.posix(tree.path) .. " -c user.name=Test -c user.email=test@example.com commit -q --allow-empty -m detached && git -C " .. quote.posix(root) .. " update-ref refs/heads/autocode/retry $(git -C " .. quote.posix(tree.path) .. " rev-parse HEAD)")
            test.is_nil(trees.remove(tree))
            shell("git -C " .. quote.posix(root) .. " rev-parse --verify autocode/retry")
            test.is_nil(trees.create(tree, "autocode/retry"))
            shell("git -C " .. quote.posix(root) .. " branch agent-result autocode/retry")
            test.is_nil(trees.remove(tree))
            test.eq(shell("git -C " .. quote.posix(root) .. " for-each-ref --format='%(refname)' refs/heads/autocode/"), "")
            shell("git -C " .. quote.posix(root) .. " rev-parse --verify agent-result")
        end)
        test.it("does not preserve an unchanged HEAD or a commit reachable through a later branch tip", function()
            local tree = trees.plan(root, "ancestor")
            test.is_nil(trees.create(tree))
            shell("git -C " .. quote.posix(root) .. " -c user.name=Test -c user.email=test@example.com commit -q --allow-empty -m later")
            test.is_nil(trees.remove(tree))
            test.eq(shell("git -C " .. quote.posix(root) .. " for-each-ref --format='%(refname)' refs/heads/autocode/"), "")
        end)
        test.it("expires preservation refs with run history in bounded pages and keeps agent branches", function()
            local prefix = uuid.v7()
            local ids = {prefix .. "-a", prefix .. "-b", prefix .. "-future"}
            local db = sql.get("app:db")
            for index, id in ipairs(ids) do
                local tree = trees.plan(root, id)
                test.is_nil(trees.create(tree))
                shell("git -C " .. quote.posix(tree.path) .. " -c user.name=Test -c user.email=test@example.com commit -q --allow-empty -m detached-" .. tostring(index))
                test.is_nil(trees.remove(tree))
                tree.removed = true
                local _, err = db:execute([[INSERT INTO chestor_autocode_runs
                    (id, owner_id, actor_id, actor_context, agent, account_id, image_id, prompt, timeout_ms, status, finished_at, worktree)
                    VALUES ($1, $2, 'test:actor', '{}', 'claude', 'account', 'image', '', 60000, 'succeeded', $3, $4)]],
                    {id, root, index == 3 and "2099-01-01T00:00:00Z" or "2000-01-01T00:00:00Z", json.encode(tree)})
                test.is_nil(err, tostring(err))
            end
            db:release()
            shell("git -C " .. quote.posix(root) .. " branch agent-branch autocode/" .. ids[1])
            test.is_true(repo.stored_run(ids[1]).worktree.removed)
            local cleanup = repo.worktree_cleanup(100)
            for _, run in ipairs(cleanup) do test.is_true(run.id ~= ids[1] and run.id ~= ids[2] and run.id ~= ids[3]) end
            local lock = root .. "/.git/refs/heads/autocode/" .. ids[1] .. ".lock"
            shell("touch " .. quote.posix(lock))
            local refused, refusal = prune.prune_runs("2001-01-01T00:00:00Z", 1)
            test.is_nil(refused); test.not_nil(refusal); test.not_nil(repo.stored_run(ids[1]))
            shell("rm -- " .. quote.posix(lock))
            local count, err, progress = prune.prune_runs("2001-01-01T00:00:00Z", 1)
            test.is_nil(err, tostring(err)); test.eq(count, 1); test.is_true(progress.needs_continue)
            test.eq(shell("git -C " .. quote.posix(root) .. " for-each-ref --format='%(refname)' refs/heads/autocode/" .. ids[1]), "")
            test.not_nil(repo.stored_run(ids[2])); test.not_nil(repo.stored_run(ids[3]))
            local result, retention_err = funcs.call("chestor.autocode.runner:retention", {})
            test.is_nil(retention_err, tostring(retention_err)); test.is_true(result.success, tostring(result.error))
            test.is_nil(repo.stored_run(ids[2])); test.not_nil(repo.stored_run(ids[3]))
            test.eq(shell("git -C " .. quote.posix(root) .. " for-each-ref --format='%(refname)' refs/heads/autocode/" .. ids[2]), "")
            shell("git -C " .. quote.posix(root) .. " rev-parse --verify agent-branch && git -C " .. quote.posix(root) .. " rev-parse --verify autocode/" .. ids[3])
        end)
        test.it("reports missing directories at the workspace boundary", function()
            local _, directory_err = paths.verify({path = root .. "/missing"})
            test.not_nil(directory_err:message():find("existing directory", 1, true), directory_err:message())
            test.eq(directory_err:details().code, "autocode.invalid_workspace")
        end)
        test.it("reports a missing repository ref at the worktree boundary", function()
            local tree = trees.plan(root, "missing-ref")
            local ref_err = trees.create(tree, "does-not-exist")
            test.not_nil(ref_err:message():find("repository ref", 1, true), ref_err:message())
            test.eq(ref_err:details().code, "autocode.invalid_repo_ref")
        end)
        test.it("preserves the host timeout kind", function()
            local state = stubs.state
            state.executor = "app:docker"
            local _, timeout_err = require("host").run({"sh", "-c", "exit 124"})
            test.is_true(errors.is(timeout_err, errors.TIMEOUT), tostring(timeout_err))
        end)
        test.it("starts from repo_ref and refuses non-git or unborn repositories", function()
            shell("git -C " .. quote.posix(root) .. " branch saved && git -C " .. quote.posix(root) .. " -c user.name=Test -c user.email=test@example.com commit -q --allow-empty -m later")
            local tree = trees.plan(root, "ref")
            test.is_nil(trees.create(tree, "saved"))
            test.eq(shell("git -C " .. quote.posix(tree.path) .. " log -1 --format=%s"), "initial")
            test.is_nil(trees.remove(tree))
            shell("rm -rf -- " .. quote.posix(root .. "/.git"))
            local none, err = trees.plan(root, "bad")
            test.is_nil(none); test.not_nil(err)
            test.not_nil(err:message():find("git repository", 1, true), err:message())
            shell("git init -q " .. quote.posix(root))
            local unborn, head_err = trees.plan(root, "unborn")
            test.is_nil(unborn); test.not_nil(head_err)
            test.not_nil(head_err:message():find("committed HEAD", 1, true), head_err:message())
        end)
    end)
end
local run_cases = test.run_cases(cases)
return {run = function(options) return run_cases(options) end}

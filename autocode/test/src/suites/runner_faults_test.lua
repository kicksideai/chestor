local test = require("test")
local stubs = require("stubs")
local resume = require("resume_subject")
local image = require("image_subject")
local runner = require("run_subject")
local function prepared()
    return {secret = "secret", revision = 1, admitted = {driver = {id = "claude"}, account = {id = "account", kind = {variable = "KEY"}},
        image = {ref = "image", home = "/home/agent", memory = "", cpus = "", pids_limit = 0, gpus = "", network = "none", extra_args = {}},
        workdir = "/work", launch = {executable = "agent", argv = {}, environment = {}, files = {}}, spec = {}}}
end
local function cases()
    test.describe("autocode worker failures", function()
        test.it("returns a native resume failure and acknowledges only successful delivery", function()
            local state = stubs.reset()
            state.run.status, state.run.flow = "succeeded", {dataflow_id = "flow", signal_id = "signal"}
            state.resume_error = true
            local result, err = resume.run({payload = {run_id = "run"}})
            test.is_nil(result)
            test.is_true(errors.is(err, errors.UNAVAILABLE))
            test.is_nil(state.delivered)
            state.resume_error = false
            local delivered, retry_err = resume.run({payload = {run_id = "run"}})
            test.is_nil(retry_err)
            test.not_nil(delivered)
            test.is_true(state.delivered)
        end)
        test.it("repairs a finished build projection without rebuilding", function()
            local state = stubs.reset()
            state.build.finished_at, state.build.status, state.build.agents = "finished", "ready", {"claude"}
            state.projection_error = true
            test.is_false(image.main({payload = {image_id = "image", build_id = "generation"}}).ok)
            state.projection_error = false
            test.is_true(image.main({payload = {image_id = "image", build_id = "generation"}}).ok)
            test.eq(state.public.status, "ready")
            test.eq(state.fetches, 0)
        end)
        test.it("rejects a stale image job before touching Docker", function()
            local state = stubs.reset()
            image.main({payload = {image_id = "image", build_id = "older"}})
            test.eq(state.fetches, 0)
        end)
        test.it("refuses an image missing the base runtime tools", function()
            local state = stubs.reset()
            state.runtime_missing = true
            local outcome = image.main({payload = {image_id = "image", build_id = "generation"}})
            test.is_true(outcome.ok)
            test.eq(state.build.status, "failed")
            test.not_nil(state.build.last_error:find("runtime prerequisites", 1, true))
        end)
        test.it("settles cancellation before container creation", function()
            local state = stubs.reset()
            state.run.cancel_requested, state.prepared = true, prepared()
            runner.main({payload = {run_id = "run"}})
            test.eq(state.run.status, "cancelled")
            test.is_nil(state.attached)
        end)
        test.it("settles cancellation between container creation and starting", function()
            local state = stubs.reset()
            state.cancel_on_reserve, state.prepared = true, prepared()
            runner.main({payload = {run_id = "run"}})
            test.eq(state.run.status, "cancelled")
            test.is_nil(state.attached)
        end)
        test.it("checks cancellation during the attached stream", function()
            local state = stubs.reset()
            state.cancel_on_attach, state.prepared = true, prepared()
            runner.main({payload = {run_id = "run"}})
            test.is_true(state.stopped > 0)
            test.eq(state.run.status, "cancelled")
        end)
        test.it("stops cancellation while attached without any output line", function()
            local state = stubs.reset()
            state.cancel_silently, state.prepared = true, prepared()
            runner.main({payload = {run_id = "run"}})
            test.is_true(state.stopped > 0)
            test.eq(state.run.status, "cancelled")
        end)
        test.it("keeps a committed workflow run successful when the wake fails", function()
            local state = stubs.reset()
            state.run.flow, state.prepared = {dataflow_id = "flow", signal_id = "signal"}, prepared()
            test.is_true(runner.main({payload = {run_id = "run"}}).ok)
            test.eq(state.run.status, "succeeded")
        end)
    end)
end
local run_cases = test.run_cases(cases)
return {run = function(options) return run_cases(options) end}

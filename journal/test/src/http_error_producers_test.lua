local test = require("test")
local thread_log = require("thread_log")
local support = require("support")
return test.run_cases(function()
    test.describe("Journal refusal ownership", function()
        test.it("types an absent journal id at the access boundary", function()
            local _, _, err = thread_log.resolve("")
            test.is_true(errors.is(err, errors.INVALID))
            test.contains(tostring(err), "journal_id is required")
        end)
        test.it("types input validation before the response adapter", function()
            local _, err = support.journal_id({ param = function() return "" end })
            test.is_true(errors.is(err, errors.INVALID))
            local _, body_err = support.body({ body = function() return "{broken" end })
            test.is_true(errors.is(body_err, errors.INVALID))
        end)
        test.it("preserves append failures after the thread access gate", function()
            local failure = errors.new({ kind = errors.PERMISSION_DENIED, message = "opaque", retryable = false })
            local log = thread_log.new({ open_threads = function() return {
                find = function() return {} end,
                append_events = function() return nil, failure end,
            } end })
            local _, err = log.append("journal", { { type = "event" } })
            test.eq(err, failure)
        end)
    end)
end)

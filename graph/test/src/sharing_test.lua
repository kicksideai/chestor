local test = require("test")
local security = require("security")
local funcs = require("funcs")
local contract = require("contract")
local crypto = require("crypto")
local sql = require("sql")
local access_ops = require("access_ops")
local share_subject = require("share_subject")

local function exec(id: string, groups: any, scope_name: string): any
    return funcs.new():with_actor(security.new_actor(id, { security_groups = groups }))
        :with_scope(security.named_scope(scope_name))
end

local function service(id: string): any
    local def, err = contract.get("kickside.component:component_service")
    test.is_nil(err)
    local inst, open_err = def:with_actor(security.new_actor(id, { security_groups = { "graph_test" } }))
        :with_scope(security.named_scope("wippy.security:process")):open()
    test.is_nil(open_err)
    return inst
end

local function probe(executor: any, op: string, input: any): any
    local result, err = executor:call("app:sharing_workspace_probe", { op = op, input = input })
    test.is_nil(err)
    return result
end

local function cases()
    test.describe("Shared workspace reads", function()
        test.it("resolves email grants to the member actor before folder and graph reads", function()
            local suffix, uuid_err = crypto.random.uuid()
            test.is_nil(uuid_err)
            local owner = "owner-" .. suffix
            local member = "member-" .. suffix
            local owner_exec = exec(owner, { "graph_test" }, "wippy.security:process")
            local member_exec = exec(member, { "app:member" }, "app:member")
            local folder = probe(owner_exec, "create", { type = "folder", name = "Northwind Email Share" })
            test.is_true(folder.ok, tostring(folder.err))
            local child = probe(owner_exec, "create", { type = "graph", name = "Northwind Shared Graph", parent_id = folder.entry.id })
            test.is_true(child.ok, tostring(child.err))
            local granted = probe(owner_exec, "grant", { id = folder.entry.id, subject_id = member .. "@northwind.example", subject_type = "user", access_mask = 1 })
            test.is_true(granted.ok, tostring(granted.err))
            local db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            local rows, rows_err = sql.builder.select("subject_id"):from("kickside_component_access")
                :where("component_id = ?", folder.entry.id):where("subject_type = ?", "user")
                :where("subject_id <> ?", owner):run_with(db):query()
            db:release()
            test.is_nil(rows_err)
            test.eq(#rows, 1)
            test.eq(rows[1].subject_id, member)
            local read = probe(member_exec, "get", { id = folder.entry.id })
            test.is_true(read.ok, "email-shared folder: " .. tostring(read.err))
            local graph, graph_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(graph_err)
            test.is_true(graph.ok, "email-shared graph: " .. tostring(graph.err))
            local revoked = probe(owner_exec, "revoke", { id = folder.entry.id, subject_id = member .. "@northwind.example", subject_type = "user" })
            test.is_true(revoked.ok, tostring(revoked.err))
            test.is_false(probe(member_exec, "get", { id = folder.entry.id }).ok)
            local denied, deny_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(deny_err)
            test.is_false(denied.ok)
        end)
        test.it("canonicalizes existing email grants before member folder and graph reads", function()
            local suffix, uuid_err = crypto.random.uuid()
            test.is_nil(uuid_err)
            local owner = "owner-" .. suffix
            local member = "member-" .. suffix
            local owner_exec = exec(owner, { "graph_test" }, "wippy.security:process")
            local member_exec = exec(member, { "app:member" }, "app:member")
            local outsider_exec = exec("outsider-" .. suffix, { "app:member" }, "app:member")
            local folder = probe(owner_exec, "create", { type = "folder", name = "Existing Email Share" })
            test.is_true(folder.ok, tostring(folder.err))
            local child = probe(owner_exec, "create", { type = "graph", name = "Existing Shared Graph", parent_id = folder.entry.id })
            test.is_true(child.ok, tostring(child.err))
            local db, db_err = sql.get("app:db")
            test.is_nil(db_err)
            local access_id, access_id_err = crypto.random.uuid()
            test.is_nil(access_id_err)
            local _, insert_err = sql.builder.insert("kickside_component_access"):set_map({
                access_id = access_id, subject_id = member .. "@northwind.example", subject_type = "user",
                component_id = folder.entry.id, source_component_id = folder.entry.id,
                access_mask = 1, inherited = 0,
            }):run_with(db):exec()
            test.is_nil(insert_err)
            local tx, tx_err = db:begin()
            test.is_nil(tx_err)
            local ok, body_err = pcall(function()
                local migrated, migrate_err = access_ops.canonicalize_email_grants(tx, function(id) return share_subject.find(id, "user") end)
                test.is_nil(migrate_err)
                test.is_true(migrated)
            end)
            if not ok then
                tx:rollback()
                db:release()
                error(body_err)
            end
            local _, commit_err = tx:commit()
            db:release()
            test.is_nil(commit_err)
            test.is_true(probe(member_exec, "get", { id = folder.entry.id }).ok)
            test.is_false(probe(outsider_exec, "get", { id = folder.entry.id }).ok)
            local graph, graph_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(graph_err)
            test.is_true(graph.ok, tostring(graph.err))
            local revoked = probe(owner_exec, "revoke", { id = folder.entry.id, subject_id = member .. "@northwind.example", subject_type = "user" })
            test.is_true(revoked.ok, tostring(revoked.err))
            test.is_false(probe(member_exec, "get", { id = folder.entry.id }).ok)
            local denied, denied_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(denied_err)
            test.is_false(denied.ok)
        end)
        test.it("honors group membership rather than the caller scope and denies reads after revoke", function()
            local suffix, uuid_err = crypto.random.uuid()
            test.is_nil(uuid_err)
            local owner = "owner-" .. suffix
            local group = "northwind-group-" .. suffix
            local owner_exec = exec(owner, { "graph_test" }, "wippy.security:process")
            local member_exec = exec("member-" .. suffix, { "app:member", group }, "app:member")
            local outsider_exec = exec("outsider-" .. suffix, { "app:member" }, "app:member")
            local folder = probe(owner_exec, "create", { type = "folder", name = "Northwind Group Share" })
            test.is_true(folder.ok, tostring(folder.err))
            local child = probe(owner_exec, "create", { type = "graph", name = "Northwind Group Graph", parent_id = folder.entry.id })
            test.is_true(child.ok, tostring(child.err))
            local granted = probe(owner_exec, "grant", { id = folder.entry.id, subject_id = group, subject_type = "group", access_mask = 1 })
            test.is_true(granted.ok, tostring(granted.err))
            test.is_true(probe(member_exec, "get", { id = folder.entry.id }).ok)
            test.is_false(probe(outsider_exec, "get", { id = folder.entry.id }).ok)
            local graph, graph_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(graph_err)
            test.is_true(graph.ok, tostring(graph.err))
            local outsider_graph, outsider_err = outsider_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(outsider_err)
            test.is_false(outsider_graph.ok)
            local revoked = probe(owner_exec, "revoke", { id = folder.entry.id, subject_id = group, subject_type = "group" })
            test.is_true(revoked.ok, tostring(revoked.err))
            test.is_false(probe(member_exec, "get", { id = folder.entry.id }).ok)
            local denied, deny_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(deny_err)
            test.is_false(denied.ok)
        end)
        test.it("honors a direct folder grant for its graph and denies reads after revoke", function()
            local suffix, uuid_err = crypto.random.uuid()
            test.is_nil(uuid_err)
            local owner = "owner-" .. suffix
            local member = "member-" .. suffix
            local owner_exec = exec(owner, { "graph_test" }, "wippy.security:process")
            local member_exec = exec(member, { "app:member" }, "app:member")
            local folder = probe(owner_exec, "create", { type = "folder", name = "Northwind Planning" })
            test.is_true(folder.ok, tostring(folder.err))
            local child = probe(owner_exec, "create", { type = "graph", name = "Northwind Graph", parent_id = folder.entry.id })
            test.is_true(child.ok, tostring(child.err))
            test.is_false(probe(member_exec, "get", { id = folder.entry.id }).ok)
            local granted, grant_err = service(owner):grant_subtree({ root_component_id = folder.entry.id,
                subject = { subject_id = member, subject_type = "user" }, access_mask = 1 })
            test.is_nil(grant_err)
            test.is_true(granted.success, "grant: " .. tostring(granted.error))
            local read = probe(member_exec, "get", { id = folder.entry.id })
            test.is_true(read.ok, "shared folder: " .. tostring(read.err))
            test.eq(read.entry.name, "Northwind Planning")
            local graph, graph_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(graph_err)
            test.is_true(graph.ok, "shared graph: " .. tostring(graph.err))
            test.eq(graph.graph.thread_id, child.entry.id)
            local revoked, revoke_err = service(owner):revoke_subtree({ root_component_id = folder.entry.id,
                subject = { subject_id = member, subject_type = "user" } })
            test.is_nil(revoke_err)
            test.is_true(revoked.success, "revoke: " .. tostring(revoked.error))
            test.is_false(probe(member_exec, "get", { id = folder.entry.id }).ok)
            local denied, deny_err = member_exec:call("app:graph_probe", { op = "state", input = { entry_id = child.entry.id } })
            test.is_nil(deny_err)
            test.is_false(denied.ok)
        end)
    end)
end
return { run = test.run_cases(cases) }
